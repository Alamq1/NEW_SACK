from pathlib import Path
import torch
from ultralytics import YOLO


# ============================================================
# PROJECT
# ============================================================

ROOT = Path(__file__).resolve().parents[2]


# ============================================================
# DATASET
# ============================================================

DATASET = (
    ROOT
    / "data"
    / "Rice Bag 10"
    / "data.yaml"
)


# ============================================================
# OUTPUT
# ============================================================

OUTPUT_DIR = (
    ROOT
    / "outputs"
)


RUN_NAME = "rice_bag_detection_v3"


# ============================================================
# MODEL
# ============================================================

MODEL = "yolo11m.pt"


# ============================================================
# HARDWARE
# ============================================================

DEVICE = 0 if torch.cuda.is_available() else "cpu"


print("=" * 70)
print("RICE BAG DETECTION V3")
print("=" * 70)

print(f"Root       : {ROOT}")
print(f"Dataset    : {DATASET}")
print(f"Model      : {MODEL}")
print(f"Device     : {DEVICE}")

if torch.cuda.is_available():

    print(
        f"GPU        : "
        f"{torch.cuda.get_device_name(0)}"
    )

else:

    print("GPU        : Not available")


# ============================================================
# VALIDATE DATASET PATH
# ============================================================

if not DATASET.exists():

    raise FileNotFoundError(
        f"\nDataset YAML not found:\n{DATASET}\n\n"
        "Check the dataset folder name."
    )


# ============================================================
# LOAD MODEL
# ============================================================

model = YOLO(MODEL)


# ============================================================
# TRAIN
# ============================================================

results = model.train(

    # --------------------------------------------------------
    # DATA
    # --------------------------------------------------------

    data=str(DATASET),

    # --------------------------------------------------------
    # MODEL INPUT
    # --------------------------------------------------------

    imgsz=1280,

    # --------------------------------------------------------
    # TRAINING
    # --------------------------------------------------------

    epochs=150,

    batch=8,

    device=DEVICE,

    workers=4,

    # --------------------------------------------------------
    # OPTIMIZATION
    # --------------------------------------------------------

    optimizer="AdamW",

    lr0=0.001,

    lrf=0.01,

    weight_decay=0.0005,

    warmup_epochs=5,

    # --------------------------------------------------------
    # AUGMENTATION
    # --------------------------------------------------------

    mosaic=0.0,

    mixup=0.0,

    copy_paste=0.0,

    degrees=3.0,

    translate=0.03,

    scale=0.15,

    shear=0.0,

    perspective=0.0,

    fliplr=0.5,

    flipud=0.0,

    hsv_h=0.01,

    hsv_s=0.30,

    hsv_v=0.20,

    # --------------------------------------------------------
    # OVERFITTING CONTROL
    # --------------------------------------------------------

    patience=30,

    dropout=0.0,

    # --------------------------------------------------------
    # DETECTION
    # --------------------------------------------------------

    max_det=300,

    # --------------------------------------------------------
    # VALIDATION
    # --------------------------------------------------------

    val=True,

    plots=True,

    # --------------------------------------------------------
    # SAVING
    # --------------------------------------------------------

    save=True,

    save_period=10,

    project=str(OUTPUT_DIR),

    name=RUN_NAME,

    exist_ok=True,

    # --------------------------------------------------------
    # REPRODUCIBILITY
    # --------------------------------------------------------

    seed=42,

    deterministic=True,

    verbose=True
)


# ============================================================
# DONE
# ============================================================

print()
print("=" * 70)
print("TRAINING COMPLETED")
print("=" * 70)

print(
    f"Best model:\n"
    f"{OUTPUT_DIR / RUN_NAME / 'weights' / 'best.pt'}"
)

print("=" * 70)